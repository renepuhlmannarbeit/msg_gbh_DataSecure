import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';
import { build } from 'esbuild';

const require = createRequire(import.meta.url);
const Ajv = require('ajv/dist/2020');
const standalone = require('ajv/dist/standalone');
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
export const output = path.join(root, 'plugins/data-secure/server/mcp-validators.generated.js');

// Read only the repository-owned literal catalogue, never user input or the
// executing server (which would start maintenance). It remains the one schema source.
export function toolSchemas() {
  const source = fs.readFileSync(path.join(root, 'plugins/data-secure/server/mcp-server.js'), 'utf8');
  const start = source.indexOf('const TOOLS=['), end = source.indexOf('\n];', start);
  if (start < 0 || end < 0) throw new Error('MCP_SCHEMA_CATALOG_MISSING');
  return JSON.parse(JSON.stringify(vm.runInNewContext(`${source.slice(start, end + 3)};TOOLS`, {}, { timeout: 1000 })))
    .map(({ name, inputSchema }) => ({ name, inputSchema }));
}

export async function generate() {
  if (require('ajv/package.json').version !== '8.20.0') throw new Error('MCP_AJV_VERSION_MISMATCH');
  const schemas = toolSchemas();
  const ajv = new Ajv({ strict: true, ownProperties: true, code: { source: true }, messages: false });
  const exports = {};
  for (const { name, inputSchema } of schemas) {
    if (Object.hasOwn(exports, name)) throw new Error('MCP_SCHEMA_DUPLICATE');
    ajv.addSchema(inputSchema, name); exports[name] = name;
  }
  const digest = crypto.createHash('sha256').update(JSON.stringify(schemas)).digest('hex');
  const source = `${standalone(ajv, exports)}\nexports.schemaDigest=${JSON.stringify(digest)};`;
  const license = fs.readFileSync(require.resolve('ajv/LICENSE'), 'utf8').trim();
  const bundle = await build({ stdin: { contents: source, resolveDir: root, sourcefile: 'mcp-validators.generated.cjs' },
    absWorkingDir: root, tsconfigRaw: {},
    plugins: [{ name: 'pinned-ajv-runtime', setup(build) {
      build.onResolve({ filter: /.*/ }, args => {
        if (args.path !== 'ajv/dist/runtime/ucs2length') throw new Error('MCP_VALIDATOR_UNEXPECTED_DEPENDENCY');
        return { path: args.path, namespace: 'pinned-ajv' };
      });
      build.onLoad({ filter: /.*/, namespace: 'pinned-ajv' }, args => ({
        contents: fs.readFileSync(require.resolve(args.path), 'utf8'), loader: 'js'
      }));
    } }],
    bundle: true, platform: 'node', target: 'node22', format: 'cjs', write: false,
    legalComments: 'inline', banner: { js: `// GENERATED by scripts/generate-mcp-validators.mjs. Do not edit.\n/*! Ajv runtime helper license:\n${license}\n*/` } });
  return bundle.outputFiles[0].text;
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const content = await generate();
  if (process.argv.includes('--write')) fs.writeFileSync(output, content);
  else if (fs.readFileSync(output, 'utf8') !== content) throw new Error('MCP_GENERATED_VALIDATORS_STALE');
  console.log('MCP validators: pinned, self-contained and schema-bound');
}
