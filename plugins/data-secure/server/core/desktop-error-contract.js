const allowed = new Set(DESKTOP_ERROR_CODES);
function desktopErrorCode(code) {
  if (allowed.has(code)) return code;
  // The early pre-history root gate runs before shared bootstrap mapping.
  // Preserve its storage-separation refusal without claiming a TCC diagnosis.
  if (code === 'PRIVACY_STORAGE_UNSAFE') return 'UNSAFE_STORAGE_LOCATION';
  if (code === 'OWNERSHIP_GUARD_BUSY') return 'STANDALONE_OWNERSHIP_CONTROL_BUSY';
  if (code === 'OWNERSHIP_GUARD_ACCESS_DENIED') return 'STANDALONE_OWNERSHIP_RUNTIME_DENIED';
  if (code === 'OWNERSHIP_GUARD_SIGNATURE_REFUSED') return 'STANDALONE_OWNERSHIP_SIGNATURE_REFUSED';
  if (code === 'OWNERSHIP_GUARD_NATIVE_LOAD_FAILED') return 'STANDALONE_OWNERSHIP_RUNTIME_LOAD_FAILED';
  if (code === 'OWNERSHIP_GUARD_UNSAFE') return 'STANDALONE_OWNERSHIP_STORAGE_UNSAFE';
  if (['OWNERSHIP_GUARD_CLOSE_UNCONFIRMED', 'OWNERSHIP_GUARD_CLOSED'].includes(code)) return 'STANDALONE_OWNERSHIP_CONTROL_UNCONFIRMED';
  if (['OWNERSHIP_GUARD_UNAVAILABLE', 'OWNERSHIP_GUARD_INTEGRITY_FAILED', 'OWNERSHIP_GUARD_INVALID',
    'OWNERSHIP_GUARD_ALREADY_CONFIGURED', 'OWNERSHIP_GUARD_INTERNAL', 'OWNERSHIP_GUARD_ASYNC_FORBIDDEN'].includes(code))
    return 'STANDALONE_OWNERSHIP_RUNTIME_INVALID';
  return 'STANDALONE_OPERATION_FAILED';
}
